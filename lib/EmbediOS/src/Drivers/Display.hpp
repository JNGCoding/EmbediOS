struct EmbediFont
{
    u16 char_width;
    u16 char_height;
    const u8* chars;
};

static EmbediFont DEFAULT_FONT =
{
    .char_width  = 8,
    .char_height = 12,
    .chars = DEFAULT_FONT_CHARS
};

class EmbediDisplay
{
public:
    enum Rotation
    {
        R0,
        R90,
        R180,
        R270,
    };

private:
    EmbediArray<DisplayColor, DISPLAY_WIDTH * DISPLAY_HEIGHT> frameBuffer;
    u32 currentLine = 0;

    bool inverse = false;
    Rotation rotated = Rotation::R0;

    EmbediFont& font = DEFAULT_FONT;
    DisplayColor fontColor{};

    u16 cursorX = 0, cursorY = 0;

    constexpr u32 coords(const u16 x, const u16 y)
    { return DISPLAY_WIDTH * y + x; }

    constexpr u32 line_index(const u16 y)
    { return DISPLAY_WIDTH * y + 0; }

    constexpr bool out_of_bounds(const u16 x, const u16 y)
    { return x > DISPLAY_WIDTH ||  y > DISPLAY_HEIGHT; }

    TFT_eSPI display = TFT_eSPI();

public:
    EmbediDisplay();

    // Set the rotation of the display
    void set_rotation(const Rotation r);

    // Set the inverse flag of the display
    void set_inverse(const bool ni);

    // Set the cursor of the display at `(x, y)` coords;
    void set_cursor(const u16 x, const u16 y);

    // Set the color of the font
    void set_font_color(const DisplayColor color);

    // This function sets the `color` value of a pixel in the framebuffer at `(x, y)` coords
    void pixel(const u16 x, const u16 y, const DisplayColor color);

    // This function draws a rectangle at `(x, y)` coords on the display
    void rect(const u16 x, const u16 y, const u16 w, const u16 h, const bool fill, const DisplayColor color);

    // This function uses `rect()` function to draw a square on the display
    void square(const u16 x, const u16 y, const u16 s, const bool fill, const DisplayColor color);

    // This function draws a circle at `(x, y)` coords on the screen
    void circle(const u16 x, const u16 y, const u16 r, const bool fill, const DisplayColor color);

    // This function draws a line starting from `(x, y)` coords to `(x1, y1)` coords
    void line(const u16 x, const u16 y, const u16 x1, const u16 y1, const DisplayColor color);

    // This function draws a horizontal line starting from `(x, y)` coords extending `w` width
    void hline(const u16 x, const u16 y, const u16 w, const bool reversed, const DisplayColor color);

    // This function draws a vertical line starting from `(x, y)` coords extending `h` height
    void vline(const u16 x, const u16 y, const u16 h, const bool reversed, const DisplayColor color);

    // This function draws a simple character onto the display
    void printc(const char character);

    // This function draws `text` onto the display
    void print(const char* text);

    // This function draws `text + '\n'` onto the display
    void println(const char* text);

    // This function has to become a service
    // inorder to draw the screen efficiently
    // as this is a non-blocking function which will draw
    // only one line at a time
    void draw_next_line();

    // This function draws the entirety of the buffer
    // in one go, this function should only be used for interrupts
    // and what not, don't use in the cooperative scheduler
    void update();

    // This function clears out the screen with the `color` value
    void clear(const DisplayColor color);

    // This function returns the virtual width of the screen
    const u16 width();

    // This function returns the virtual height of the screen
    const u16 height();

    // This function returns a color value of a pixel at `(x, y)` coords from the framebuffer
    const DisplayColor& get_pixel(const u16 x, const u16 y);
};
